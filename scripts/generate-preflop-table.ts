/**
 * Precompute how strong each of the 169 starting hands is.
 *
 * You can be dealt 1,326 different two-card combinations, but only 169 that
 * play differently - the ace-king of hearts and the ace-king of spades are the
 * same hand. We measure each one's equity against a uniformly random opponent
 * hand and write the results out as a plain table the app imports.
 *
 * This is the pattern worth noticing: heavy computation happens ONCE, here,
 * offline. The app then just reads an array. Nobody's browser ever repeats this
 * work. Real trading systems are organized the same way - expensive research
 * produces small tables, and the fast path only ever looks things up.
 */
import { makeDeck, handNotation, RANK_CHARS, makeCard } from '../src/lib/poker/cards';
import { rangeEquity } from '../src/lib/poker/equity';
import { writeFileSync } from 'node:fs';

const TRIALS = 60000;

// Every two-card combination in the deck, used as "a completely random hand".
const allCombos: number[][] = [];
const deck = makeDeck();
for (let i = 0; i < 52; i++) for (let j = i + 1; j < 52; j++) allCombos.push([deck[i], deck[j]]);

/** One representative combo for each of the 169 hands, plus how many exist. */
function representative(hand: string): { cards: number[]; combos: number } {
  const r1 = RANK_CHARS.indexOf(hand[0]);
  const r2 = RANK_CHARS.indexOf(hand[1]);
  if (r1 === r2) return { cards: [makeCard(r1, 0), makeCard(r2, 1)], combos: 6 };
  const suited = hand[2] === 's';
  return suited
    ? { cards: [makeCard(r1, 0), makeCard(r2, 0)], combos: 4 }
    : { cards: [makeCard(r1, 0), makeCard(r2, 1)], combos: 12 };
}

const hands: string[] = [];
for (let i = 12; i >= 0; i--) {
  for (let j = 12; j >= 0; j--) {
    if (i === j) hands.push(RANK_CHARS[i] + RANK_CHARS[j]);
    else if (i > j) hands.push(RANK_CHARS[i] + RANK_CHARS[j] + 's');
    else hands.push(RANK_CHARS[j] + RANK_CHARS[i] + 'o');
  }
}
const unique = [...new Set(hands)];
console.log(`Measuring ${unique.length} starting hands at ${TRIALS.toLocaleString()} trials each...`);

const rows: Array<{ hand: string; equity: number; combos: number }> = [];
const t0 = performance.now();
for (const hand of unique) {
  const { cards, combos } = representative(hand);
  const r = rangeEquity(cards, allCombos, [], TRIALS, 999);
  rows.push({ hand, equity: r.equity, combos });
}
console.log(`Done in ${((performance.now() - t0) / 1000).toFixed(1)}s\n`);

// Sort strongest first, then assign each hand a percentile by COMBO count, not
// by position in the list. This matters: pairs are only 6 combos each while
// offsuit hands are 12, so "the top 15% of hands" has to be weighted by how
// often each one is actually dealt.
rows.sort((a, b) => b.equity - a.equity);
let cumulative = 0;
const table: Record<string, { eq: number; pct: number }> = {};
for (const row of rows) {
  cumulative += row.combos;
  table[row.hand] = {
    eq: Math.round(row.equity * 10000) / 10000,
    pct: Math.round((cumulative / 1326) * 10000) / 10000,
  };
}

console.log('Strongest ten:');
for (const r of rows.slice(0, 10)) {
  console.log(`  ${r.hand.padEnd(4)} ${(r.equity * 100).toFixed(1)}%  top ${(table[r.hand].pct * 100).toFixed(1)}%`);
}
console.log('\nWeakest five:');
for (const r of rows.slice(-5)) {
  console.log(`  ${r.hand.padEnd(4)} ${(r.equity * 100).toFixed(1)}%`);
}

const out = `/**
 * AUTO-GENERATED by scripts/generate-preflop-table.ts - do not edit by hand.
 *
 * For each of the 169 distinct starting hands:
 *   eq  = equity against a uniformly random opponent hand (${TRIALS.toLocaleString()} simulations)
 *   pct = where it lands when hands are ranked strongest-first, weighted by how
 *         many combinations of each exist. So pct 0.15 means "this hand is in
 *         the top 15% of all hands you'll be dealt".
 *
 * The pct column is what makes "play the top 20%" a sentence the code can act on.
 */
export interface PreflopEntry { eq: number; pct: number }

export const PREFLOP_STRENGTH: Record<string, PreflopEntry> = ${JSON.stringify(table, null, 2)};

/** Equity against a random hand, 0..1. */
export function preflopEquity(hand: string): number {
  return PREFLOP_STRENGTH[hand]?.eq ?? 0.35;
}

/** 0..1, where smaller means stronger. 0.05 = top 5% of starting hands. */
export function preflopPercentile(hand: string): number {
  return PREFLOP_STRENGTH[hand]?.pct ?? 1;
}
`;
writeFileSync('src/lib/poker/preflopStrength.ts', out);
console.log('\nWrote src/lib/poker/preflopStrength.ts');
